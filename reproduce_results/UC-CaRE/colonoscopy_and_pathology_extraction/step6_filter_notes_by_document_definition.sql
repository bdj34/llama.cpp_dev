DATEPART(YEAR, t1.ReferenceDateTime) AS PROC_YEAR
INTO <SCHEMA>.COLONOSCOPY_2025_04_02
FROM <SCHEMA>.NoteTable T1
INNER JOIN <SCHEMA>.colonoscopyTitleSID T2
ON T1.TIUDocumentDefinitionSID  = T2.TIUDocumentDefinitionSID
CREATE CLUSTERED COLUMNSTORE INDEX CCI ON <SCHEMA>.COLONOSCOPY_2025_04_02

